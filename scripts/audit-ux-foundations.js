const fs = require('node:fs');
const path = require('node:path');

const SOURCE_EXTENSIONS = new Set(['.js', '.jsx', '.css', '.html']);
const METRICS = [
  'rawHexColors',
  'inlineStyleObjects',
  'fontFamilyDeclarations',
  'emojiGlyphs',
  'directReactIconImports',
  'sharedUiImports',
];

function countMatches(source, expression) {
  return Array.from(source.matchAll(expression)).length;
}

function auditSource(source) {
  return {
    rawHexColors: countMatches(source, /#[0-9a-fA-F]{3,8}\b/g),
    inlineStyleObjects: countMatches(source, /style\s*=\s*\{\{/g),
    fontFamilyDeclarations: countMatches(source, /fontFamily\s*:|font-family\s*:/g),
    emojiGlyphs: countMatches(source, /\p{Extended_Pictographic}/gu),
    directReactIconImports: countMatches(source, /from\s+['"]react-icons\//g),
    sharedUiImports: countMatches(source, /from\s+['"][^'"]*components\/ui\//g),
  };
}

function walk(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap(function (entry) {
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) return walk(fullPath);
    return SOURCE_EXTENSIONS.has(path.extname(entry.name)) ? [fullPath] : [];
  });
}

function sumMetrics(rows) {
  return rows.reduce(function (totals, row) {
    METRICS.forEach(function (metric) { totals[metric] += row[metric]; });
    return totals;
  }, Object.fromEntries(METRICS.map(function (metric) { return [metric, 0]; })));
}

function renderReport(audit) {
  const metricLabels = {
    rawHexColors: 'Raw hex color occurrences',
    inlineStyleObjects: 'Inline React style objects',
    fontFamilyDeclarations: 'Font-family declarations',
    emojiGlyphs: 'Emoji/pictographic glyph occurrences',
    directReactIconImports: 'Direct react-icons imports',
    sharedUiImports: 'Shared UI primitive imports',
  };
  const metricRows = METRICS.map(function (metric) {
    return `| ${metricLabels[metric]} | ${audit.totals[metric]} |`;
  }).join('\n');
  const topRows = audit.topFiles.length
    ? audit.topFiles.map(function (row) {
      return `| \`${row.file}\` | ${row.rawHexColors} | ${row.inlineStyleObjects} | ${row.fontFamilyDeclarations} | ${row.emojiGlyphs} | ${row.directReactIconImports} |`;
    }).join('\n')
    : '| None | 0 | 0 | 0 | 0 | 0 |';

  return `# Contemporary UX Baseline\n\nGenerated by \`node scripts/audit-ux-foundations.js\` on ${audit.generatedAt}. Counts are migration indicators, not automatic defects.\n\n## Source inventory\n\nFiles scanned: **${audit.filesScanned}** under \`frontend/src\`.\n\n| Indicator | Count |\n|---|---:|\n${metricRows}\n\n## Highest-concentration files\n\n| File | Hex | Inline styles | Font declarations | Emoji | Direct icon imports |\n|---|---:|---:|---:|---:|---:|\n${topRows}\n\n## Screen and state migration matrix\n\n| Wave | Surfaces | Required states |\n|---|---|---|\n| Pilot | API-driven Home | focused/all teams, loading, cached/offline, empty, error, disabled actions |\n| A | My Team, roster, player profiles | empty, incomplete profile, long names, read-only role |\n| B | Schedule, event details | upcoming/past, practice/game, home/away, canceled |\n| C | Game Day entry, lineup management | ready/draft/unavailable, locked/unlocked, share |\n| D | Support, Account, Help, Feedback, Links, About, Updates, Legal | search, accordions, submission, long content |\n| E | Auth and access | signed out, pending, rejected, memberless, validation error |\n| F | Live Game Mode and scoring | scorer/viewer, offline, conflicts, modals, landscape |\n\n## Verification gates\n\n- WCAG AA contrast, keyboard-visible focus, and 44px touch targets.\n- Responsive review at 375px and 393px plus Game Day landscape.\n- Installed-PWA safe areas and pinned navigation.\n- Loading, empty, error, offline, disabled, and permission-restricted states.\n- Targeted tests, full frontend tests, lint, and build.\n- Full Game Day Validation for any Game Day or scoring migration.\n- Header, footer, wordmark, and brand icon remain unchanged unless separately approved.\n`;
}

function run(rootDirectory) {
  const sourceRoot = path.join(rootDirectory, 'frontend', 'src');
  const rows = walk(sourceRoot).map(function (filePath) {
    return Object.assign(
      { file: path.relative(rootDirectory, filePath).replaceAll('\\', '/') },
      auditSource(fs.readFileSync(filePath, 'utf8')),
    );
  });
  const scored = rows.map(function (row) {
    const score = row.rawHexColors + row.inlineStyleObjects + row.fontFamilyDeclarations + row.emojiGlyphs + row.directReactIconImports;
    return Object.assign({ score }, row);
  }).sort(function (a, b) { return b.score - a.score; });
  const now = new Date();
  const localDate = [now.getFullYear(), String(now.getMonth() + 1).padStart(2, '0'), String(now.getDate()).padStart(2, '0')].join('-');
  const audit = {
    generatedAt: localDate,
    filesScanned: rows.length,
    totals: sumMetrics(rows),
    topFiles: scored.slice(0, 15),
  };
  const reportPath = path.join(rootDirectory, 'docs', 'product', 'CONTEMPORARY_UX_BASELINE.md');
  fs.writeFileSync(reportPath, renderReport(audit));
  return reportPath;
}

if (require.main === module) {
  console.log(run(path.resolve(__dirname, '..')));
}

module.exports = { auditSource, renderReport, run };
